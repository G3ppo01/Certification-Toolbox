<#
This script is responsible for aggregating multiple md files into a single one
It should take all of the md files in a given directory and combine them into a single md file, preserving the order of the files based on their names.

The outputed file will start with a header that includes the current date and time, and then list the contents of each md file in order.
The outputed file will be used as a source for google notebooks (Wich limits the number of sources).
